import { readFile, readdir, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';

const skillRoot = new URL('../../skills/lightroom-agent/', import.meta.url);
const files = ['SKILL.md', ...(await readdir(new URL('references/', skillRoot)))
  .sort().map((name) => `references/${name}`)];
const sources = new Map(await Promise.all(files.map(async (file) =>
  [file, (await readFile(new URL(file, skillRoot), 'utf8')).replace(/\r\n/g, '\n')])));

function fromSkillRoot(file, target) {
  if (/^[a-z][a-z0-9+.-]*:/i.test(target)) {
    return target;
  }
  const [path, fragment] = target.split('#');
  const resolved = path ? posix.join(posix.dirname(file), path) : file;
  if (!sources.has(resolved)) {
    throw new Error(`${file} links to ${target}, which the prompt does not include`);
  }
  return fragment === undefined ? resolved : `${resolved}#${fragment}`;
}

const text = files.map((file) => `# ${file}\n\n${sources.get(file)
  .replace(/\]\(([^)\s]+)\)/g, (_, target) => `](${fromSkillRoot(file, target)})`)}`)
  .join('\n\n').trim();

const skill = sources.get('SKILL.md');
const frontmatter = /^---\nname: (.+)\ndescription: (.+)\n---\n/.exec(skill);
const title = /^# (.+)$/m.exec(skill.slice(frontmatter?.[0].length ?? 0));
if (!frontmatter || !title) {
  throw new Error('SKILL.md needs front matter with name and description, then a title');
}
const prompt = { name: frontmatter[1], title: title[1], description: frontmatter[2] };

await writeFile(new URL('../src/skill-content.ts', import.meta.url),
  `// Generated by scripts/generate-skill.mjs.\nexport const SKILL_PROMPT = ${JSON.stringify(prompt)};\nexport const SKILL_TEXT = ${JSON.stringify(text)};\n`);

const manifestUrl = new URL('../../mcpb/manifest.json', import.meta.url);
const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'));
manifest.prompts = [{ name: prompt.name, description: prompt.description, text }];
await writeFile(manifestUrl, `${JSON.stringify(manifest, null, 2)}\n`);
